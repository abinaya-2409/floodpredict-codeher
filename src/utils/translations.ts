/**
 * Interface strings, in the languages the modelled cities actually speak.
 *
 * A flood warning that arrives in a language you do not read is not a
 * warning, and the people this application is weighted toward - low-income
 * households, elderly residents, those without a vehicle - are the least
 * likely to be reading English. So the language set is not decorative: it
 * covers one language per modelled city, and the app offers the right one by
 * default when you switch city.
 *
 * These translations need review by native speakers before any operational
 * use. They are careful, but "careful" is not the standard an emergency
 * broadcast should be held to.
 */

